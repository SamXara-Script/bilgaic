const textOriginals = new WeakMap()
const translatedAttributes = ['aria-label', 'placeholder', 'title']

export function getLanguageOption(value) {
  return languageOptions.find((option) => option.id === value) || languageOptions[0]
}

export function translateText(text, languageId) {
  const language = translations[languageId] ? languageId : defaultLanguageId
  if (language === defaultLanguageId || typeof text !== 'string') return text

  const leading = text.match(/^\s*/)?.[0] || ''
  const trailing = text.match(/\s*$/)?.[0] || ''
  const phrase = text.trim()
  if (!phrase) return text

  return `${leading}${translatePhrase(phrase, language)}${trailing}`
}

export function formatLanguageChangeNotice(languageId, option) {
  if (languageId === 'ru') return `Язык изменен: ${translatePhrase(option.label, 'ru')}.`
  return `Language changed to ${option.label}.`
}

export function observePageTranslations(root, languageId) {
  if (!root || typeof MutationObserver === 'undefined') return () => {}

  let frameId = 0
  const run = () => {
    if (frameId) window.cancelAnimationFrame(frameId)
    frameId = window.requestAnimationFrame(() => translateRoot(root, languageId))
  }
  const observer = new MutationObserver(run)
  observer.observe(root, { childList: true, subtree: true, characterData: true, attributes: true, attributeFilter: translatedAttributes })
  run()

  return () => {
    observer.disconnect()
    if (frameId) window.cancelAnimationFrame(frameId)
  }
}

function translateRoot(root, languageId) {
  translateTextNodes(root, languageId)
  translateElementAttributes(root, languageId)
}

function translateTextNodes(root, languageId) {
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
    acceptNode(node) {
      if (!node.nodeValue?.trim()) return NodeFilter.FILTER_REJECT
      if (node.parentElement?.closest('script, style, svg, [data-no-translate]')) return NodeFilter.FILTER_REJECT
      return NodeFilter.FILTER_ACCEPT
    },
  })

  const nodes = []
  while (walker.nextNode()) nodes.push(walker.currentNode)

  for (const node of nodes) {
    const original = textOriginals.get(node) || node.nodeValue
    textOriginals.set(node, original)
    const translated = translateText(original, languageId)
    if (node.nodeValue !== translated) node.nodeValue = translated
  }
}

function translateElementAttributes(root, languageId) {
  const elements = root.querySelectorAll(translatedAttributes.map((attribute) => `[${attribute}]`).join(','))
  for (const element of elements) {
    if (element.closest('svg, [data-no-translate]')) continue

    for (const attribute of translatedAttributes) {
      const value = element.getAttribute(attribute)
      if (!value) continue

      const originalAttribute = `data-i18n-original-${attribute}`
      if (!element.hasAttribute(originalAttribute)) element.setAttribute(originalAttribute, value)

      const original = element.getAttribute(originalAttribute) || value
      const translated = translateText(original, languageId)
      if (value !== translated) element.setAttribute(attribute, translated)
    }
  }
}

function translatePhrase(phrase, languageId) {
  const dictionary = translations[languageId] || {}
  if (dictionary[phrase]) return dictionary[phrase]
  if (languageId !== 'ru') return phrase

  for (const { pattern, translate } of patternTranslations) {
    const match = phrase.match(pattern)
    if (match) return translate(match, languageId)
  }

  return phrase
}

